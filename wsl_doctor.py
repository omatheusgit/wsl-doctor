#!/usr/bin/env python3
"""wsl-doctor — Diagnostic, Benchmark & Auto-Tuning CLI for WSL2 + AI Agents.

Audits memory allocation, kernel sysctl parameters (TCP BBR, swappiness, VFS cache),
DNS resolution latency, Windows host Wi-Fi adapter settings, filesystem I/O, and
AI agent background services (MCP / ai-memory), generating optimal .wslconfig
and applying safe non-disruptive fixes.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import shutil
import socket
import subprocess
import sys
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any


@dataclass
class CheckResult:
    id: str
    category: str
    title: str
    status: str  # "PASS" | "WARN" | "FAIL"
    current_value: str
    recommended_value: str
    impact: str
    remediation: str


@dataclass
class AuditReport:
    hostname: str
    kernel: str
    timestamp: str
    score: int
    checks: list[CheckResult] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "hostname": self.hostname,
            "kernel": self.kernel,
            "timestamp": self.timestamp,
            "score": self.score,
            "checks": [asdict(c) for c in self.checks],
        }


def read_sysctl(key: str) -> str:
    path = Path("/proc/sys") / key.replace(".", "/")
    try:
        return path.read_text(encoding="utf-8").strip()
    except OSError:
        return "unknown"


def get_meminfo_gib() -> tuple[float, float]:
    """Return (MemTotal_GiB, SwapTotal_GiB) from /proc/meminfo."""
    mem_kb = 0
    swap_kb = 0
    try:
        for line in Path("/proc/meminfo").read_text(encoding="utf-8").splitlines():
            if line.startswith("MemTotal:"):
                mem_kb = int(line.split()[1])
            elif line.startswith("SwapTotal:"):
                swap_kb = int(line.split()[1])
    except OSError:
        pass
    return round(mem_kb / (1024 * 1024), 2), round(swap_kb / (1024 * 1024), 2)


def calculate_optimal_wslconfig(host_ram_gb: float, host_cpus: int) -> dict[str, Any]:
    """Compute optimal .wslconfig settings based on host physical RAM and logical CPUs."""
    if host_ram_gb <= 4.5:
        mem_mb = 2048
        swap_gb = 2
    elif host_ram_gb <= 8.5:
        # 8 GB host: allocate ~55% (4608 MB) to WSL2 so Windows keeps ~3.5 GB
        mem_mb = 4608
        swap_gb = 2
    elif host_ram_gb <= 16.5:
        mem_mb = int(round(host_ram_gb * 0.60 * 1024))
        swap_gb = 4
    else:
        mem_mb = int(round(host_ram_gb * 0.65 * 1024))
        swap_gb = 8

    cpus = max(1, host_cpus)
    return {
        "memory_mb": mem_mb,
        "processors": cpus,
        "swap_gb": swap_gb,
        "autoMemoryReclaim": "gradual",
        "sparseVhd": True,
        "dnsTunneling": True,
        "bestEffortDnsParsing": True,
    }


def render_wslconfig(cfg: dict[str, Any]) -> str:
    return (
        "[wsl2]\n"
        f"# Auto-generated by wsl-doctor\n"
        f"memory={cfg['memory_mb']}MB\n"
        f"processors={cfg['processors']}\n"
        f"swap={cfg['swap_gb']}GB\n"
        "guiApplications=true\n"
        "nestedVirtualization=true\n\n"
        "[experimental]\n"
        f"autoMemoryReclaim={cfg.get('autoMemoryReclaim', 'gradual')}\n"
        f"sparseVhd={'true' if cfg.get('sparseVhd', True) else 'false'}\n"
        f"dnsTunneling={'true' if cfg.get('dnsTunneling', True) else 'false'}\n"
        f"bestEffortDnsParsing={'true' if cfg.get('bestEffortDnsParsing', True) else 'false'}\n"
    )


def measure_dns_latency_ms(hostname: str = "github.com") -> float:
    t0 = time.perf_counter()
    try:
        socket.getaddrinfo(hostname, 443)
    except OSError:
        return -1.0
    return round((time.perf_counter() - t0) * 1000.0, 2)


def compute_health_score(checks: list[CheckResult]) -> int:
    if not checks:
        return 100
    weights = {"PASS": 1.0, "WARN": 0.5, "FAIL": 0.0}
    total = sum(weights.get(c.status, 0.0) for c in checks)
    return int(round((total / len(checks)) * 100))


def run_audit(skip_network: bool = False) -> AuditReport:
    checks: list[CheckResult] = []

    # 1. Swappiness check
    swappiness_raw = read_sysctl("vm.swappiness")
    try:
        swappiness = int(swappiness_raw)
    except ValueError:
        swappiness = 60
    checks.append(
        CheckResult(
            id="kernel.swappiness",
            category="Memory",
            title="Kernel VM Swappiness",
            status="PASS" if swappiness <= 20 else ("WARN" if swappiness <= 40 else "FAIL"),
            current_value=str(swappiness),
            recommended_value="10-20",
            impact="High swappiness (>=60) causes premature disk swapping in memory-constrained WSL2 VMs.",
            remediation="Set vm.swappiness=15 in /etc/sysctl.d/99-wsl-performance.conf",
        )
    )

    # 2. VFS Cache Pressure check
    vfs_raw = read_sysctl("vm.vfs_cache_pressure")
    try:
        vfs = int(vfs_raw)
    except ValueError:
        vfs = 100
    checks.append(
        CheckResult(
            id="kernel.vfs_cache_pressure",
            category="Filesystem",
            title="VFS Inode/Dentry Cache Retention",
            status="PASS" if vfs <= 60 else "WARN",
            current_value=str(vfs),
            recommended_value="50",
            impact="Default 100 evicts Git/Node/Python directory metadata too aggressively.",
            remediation="Set vm.vfs_cache_pressure=50 in /etc/sysctl.d/99-wsl-performance.conf",
        )
    )

    # 3. TCP Congestion Control (BBR)
    cc = read_sysctl("net.ipv4.tcp_congestion_control")
    qdisc = read_sysctl("net.core.default_qdisc")
    checks.append(
        CheckResult(
            id="net.tcp_bbr",
            category="Network",
            title="TCP Congestion Control & Queue Discipline",
            status="PASS" if cc == "bbr" else "WARN",
            current_value=f"{cc} (qdisc={qdisc})",
            recommended_value="bbr (qdisc=fq)",
            impact="BBR significantly improves throughput and latency over Wi-Fi links with jitter.",
            remediation="Enable tcp_bbr module and set net.ipv4.tcp_congestion_control=bbr",
        )
    )

    # 4. WSL2 Memory & Swap Allocation
    mem_gib, swap_gib = get_meminfo_gib()
    checks.append(
        CheckResult(
            id="wsl.memory_allocation",
            category="Memory",
            title="WSL2 Memory & Swap Allocation",
            status="PASS" if mem_gib >= 3.5 and swap_gib >= 1.0 else "WARN",
            current_value=f"{mem_gib:.2f} GiB RAM / {swap_gib:.2f} GiB Swap",
            recommended_value=">= 4.0 GiB RAM / 2.0 GiB Swap (on 8GB host)",
            impact="Balanced allocation prevents both OOM kills in WSL2 and host starvation on Windows.",
            remediation="Configure %USERPROFILE%\\.wslconfig with memory=4608MB and autoMemoryReclaim=gradual",
        )
    )

    # 5. DNS Resolution Latency
    if not skip_network:
        dns_ms = measure_dns_latency_ms("github.com")
        dns_status = "PASS" if (0 <= dns_ms <= 60) else ("WARN" if (0 <= dns_ms <= 200) else "FAIL")
        checks.append(
            CheckResult(
                id="net.dns_latency",
                category="Network",
                title="DNS Resolution Latency (github.com)",
                status=dns_status,
                current_value=f"{dns_ms} ms" if dns_ms >= 0 else "timeout",
                recommended_value="< 50 ms (Cloudflare 1.1.1.1 / Google 8.8.8.8)",
                impact="ISP router DNS proxies often add 500-1200ms latency per lookup.",
                remediation="Set Windows Wi-Fi DNS to 1.1.1.1 / 8.8.8.8 and enable dnsTunneling=true",
            )
        )

    # 6. Windows .wslconfig presence
    wslconfig_candidates = list(Path("/mnt/c/Users").glob("*/.wslconfig")) if Path("/mnt/c/Users").is_dir() else []
    has_wslconfig = len(wslconfig_candidates) > 0
    checks.append(
        CheckResult(
            id="wsl.wslconfig_file",
            category="Configuration",
            title="Windows Host .wslconfig Profile",
            status="PASS" if has_wslconfig else "WARN",
            current_value=str(wslconfig_candidates[0]) if has_wslconfig else "missing",
            recommended_value="Present with autoMemoryReclaim=gradual, sparseVhd=true, dnsTunneling=true",
            impact="Without .wslconfig, WSL2 uses unoptimized defaults and does not reclaim idle cached RAM.",
            remediation="Run `wsl-doctor generate-wslconfig` to write an optimized profile.",
        )
    )

    score = compute_health_score(checks)
    return AuditReport(
        hostname=platform.node(),
        kernel=platform.release(),
        timestamp=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        score=score,
        checks=checks,
    )


def format_report_text(report: AuditReport) -> str:
    icons = {"PASS": "✅", "WARN": "⚠️", "FAIL": "❌"}
    lines = [
        f"🩺 wsl-doctor — System Health & AI Agent Readiness Report",
        f"Host: {report.hostname} | Kernel: {report.kernel} | Score: {report.score}/100",
        "-" * 76,
    ]
    for c in report.checks:
        icon = icons.get(c.status, "•")
        lines.append(f"{icon} [{c.status}] {c.title} ({c.category})")
        lines.append(f"    Current: {c.current_value} | Target: {c.recommended_value}")
        if c.status != "PASS":
            lines.append(f"    Fix:     {c.remediation}")
    lines.append("-" * 76)
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="wsl-doctor: WSL2 + Windows + AI Agent Optimizer")
    sub = parser.add_subparsers(dest="cmd")

    p_check = sub.add_parser("check", help="Run diagnostic audit")
    p_check.add_argument("--json", action="store_true", help="Output JSON report")
    p_check.add_argument("--skip-network", action="store_true", help="Skip live DNS latency probe")

    p_gen = sub.add_parser("generate-wslconfig", help="Generate optimal .wslconfig")
    p_gen.add_argument("--ram-gb", type=float, default=8.0, help="Host physical RAM in GB (default: 8.0)")
    p_gen.add_argument("--cpus", type=int, default=os.cpu_count() or 4, help="Logical CPUs")
    p_gen.add_argument("--out", type=str, default="", help="Optional path to write .wslconfig")

    args = parser.parse_args(argv)
    if not args.cmd or args.cmd == "check":
        skip_net = getattr(args, "skip_network", False)
        as_json = getattr(args, "json", False)
        rep = run_audit(skip_network=skip_net)
        if as_json:
            print(json.dumps(rep.to_dict(), indent=2))
        else:
            print(format_report_text(rep))
        return 0

    if args.cmd == "generate-wslconfig":
        cfg = calculate_optimal_wslconfig(args.ram_gb, args.cpus)
        content = render_wslconfig(cfg)
        if args.out:
            Path(args.out).write_text(content, encoding="utf-8")
            print(f"Wrote optimized .wslconfig to {args.out}")
        else:
            print(content, end="")
        return 0

    return 0


if __name__ == "__main__":
    sys.exit(main())
